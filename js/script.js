// --- Animations (Counter & Intersection Observer) ---
function animateCounter(el, targetValue, suffix) {
  let currentValue = 0;
  const step = Math.max(1, Math.ceil(targetValue / 40));
  const timer = setInterval(() => {
    currentValue = Math.min(targetValue, currentValue + step);
    el.textContent = currentValue + suffix;
    if (currentValue >= targetValue) clearInterval(timer);
  }, 30);
}

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const target = entry.target;
      target.classList.add("in");
      target.querySelectorAll("[data-w]").forEach((bar) => (bar.style.width = bar.dataset.w + "%"));
      target.querySelectorAll("[data-n]").forEach((counter) => {
        const num = parseInt(counter.dataset.n);
        const suffix = counter.dataset.n.replace(/\d/g, "");
        animateCounter(counter, num, suffix);
      });
      observer.unobserve(target);
    });
  },
  { threshold: 0.15 }
);

